// weekly-planner

let dayNumber = 4;

switch (dayNumber) {
    case 1:
        console.log("Day " + dayNumber + ": Monday - FREE TIME");
        break;

    case 2:
        console.log("Day " + dayNumber + ": Tuesday - CLASS");
        break;

    case 3:
        console.log("Day " + dayNumber + ": Wednesday - FREE TIME");
        break;

    case 4:
        console.log("Day " + dayNumber + ": Thursday - CLASS");
        break;

    case 5:
        console.log("Day " + dayNumber + ": Friday - FREE TIME");
        break;

    case 6:
        console.log("Day " + dayNumber + ": Saturday - CLASS");
        break;

    case 7:
        console.log("Day " + dayNumber + ": Sunday - FREE TIME");
        break;

    default:
        console.log("Invalid day number");

}